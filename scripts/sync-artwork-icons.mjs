// Run from any directory. Android receives a checked-in native vector snapshot.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(readFileSync(resolve(root, 'web/app/icons/artwork-icons.json'), 'utf8'));
const target = resolve(root, '../mvbar-android/app/src/main/java/com/mvbar/android/ui/components/ArtworkIcons.kt');
if (!existsSync(dirname(target))) throw new Error('Expected sibling mvbar-android checkout was not found.');
const vectors = Object.entries(source.icons).map(([name, path]) => `    val ${name[0].toUpperCase() + name.slice(1)}: ImageVector by lazy {
        ImageVector.Builder("MVBar${name}", ${source.viewport}.dp, ${source.viewport}.dp, ${source.viewport}f, ${source.viewport}f)
            .addPath(
                pathData = PathParser().parsePathString("${path}").toNodes(),
                fill = null,
                stroke = SolidColor(Color.Black),
                strokeLineWidth = ${source.strokeWidth}f,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Round
            ).build()
    }`).join('\n\n');
const output = `// Generated by mvbar/scripts/sync-artwork-icons.mjs. Do not edit by hand.
// Source: mvbar/web/app/icons/artwork-icons.json (version ${source.version}).
package com.mvbar.android.ui.components

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

object ArtworkIcons {
${vectors}
}
`;
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('Android artwork icons are out of sync. Run node scripts/sync-artwork-icons.mjs.');
  console.log('Web and Android artwork geometry match.');
} else {
  writeFileSync(target, output);
  console.log(`Generated ${target}`);
}
